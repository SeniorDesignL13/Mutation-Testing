import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected


@pytest.mark.usefixtures("database")
def test_models_match_migrations() -> None:
    try:
        command.check(Config(toml_file="pyproject.toml"))
    except AutogenerateDiffsDetected as exc:
        pytest.fail(
            "The models in src/mtlj/api/models/ don't match the migrations. Create one with:\n"
            '  alembic revision --autogenerate -m "describe your change"\n'
            f"{exc}"
        )
